type Migration struct {
	Version     string
	Name        string
	AppliedAt   *time.Time
	RollbackSQL string
}

type MigrationFile struct {
	Version string
	Name    string
	UpSQL   string
	DownSQL string
}

type Migrator interface {
	RunMigrations(ctx context.Context) error
	Rollback(ctx context.Context, steps int) error
	GetAppliedMigrations(ctx context.Context) ([]Migration, error)
	GenerateMigrationFiles(config *domain.Config, outputDir string, fs domain.FileSystemPort) error
}

type PostgresMigrator struct {
	DBURL         string
	DatabaseType  string
	MigrationsDir string
}

type MongoMigrator struct {
	DBURL         string
	DatabaseType  string
	MigrationsDir string
}

func NewPostgresMigrator(dbURL, migrationsDir string) *PostgresMigrator {
	return &PostgresMigrator{
		DBURL:         dbURL,
		DatabaseType:  "postgresql",
		MigrationsDir: migrationsDir,
	}
}

func NewMongoMigrator(dbURL, migrationsDir string) *MongoMigrator {
	return &MongoMigrator{
		DBURL:         dbURL,
		DatabaseType:  "mongodb",
		MigrationsDir: migrationsDir,
	}
}

