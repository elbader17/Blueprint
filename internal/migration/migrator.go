type mongoIndex struct {
	Name   string
	Fields string
}

func (m *MongoMigrator) GenerateMigrationFiles(config *domain.Config, outputDir string, fs domain.FileSystemPort) error {
	version := time.Now().Format("20060102150405")
	migrationName := "initial_schema"

	dir := filepath.Join(outputDir, "mongodb")
	if err := fs.MkdirAll(dir); err != nil {
		return fmt.Errorf("failed to create migrations directory: %w", err)
	}

	var allIndexes []mongoIndex
	for _, model := range config.Models {
		for relName, relType := range model.Relations {
			if strings.HasPrefix(relType, "hasMany") {
				parts := strings.Split(relType, ":")
				if len(parts) == 2 {
					idx := mongoIndex{
						Name:   relName + "_" + parts[1],
						Fields: fmt.Sprintf(`"%s": 1`, relName),
					}
					allIndexes = append(allIndexes, idx)
				}
			}
		}
	}

	upSQL := fmt.Sprintf(`// Migration: %s
// Version: %s
// Generated by Blueprint

// Schema migrations collection
db.createCollection("schema_migrations");

db.schema_migrations.createIndex({ "_version": 1 }, { unique: true });

`, migrationName, version)

	for _, model := range config.Models {
		upSQL += fmt.Sprintf(`// Collection: %s
db.createCollection("%s");

db.%s.createIndex({ "_id": 1 });

`, model.Name, model.Name, model.Name)

		for _, idx := range allIndexes {
			upSQL += fmt.Sprintf(`db.%s.createIndex({ %s }, { name: "idx_%s" });

`, model.Name, idx.Fields, idx.Name)
		}
	}

	downSQL := fmt.Sprintf(`// Rollback: %s
// Version: %s
// Generated by Blueprint

db.schema_migrations.drop();

`, migrationName, version)

	upFilePath := filepath.Join(dir, fmt.Sprintf("%s_%s.up.js", version, migrationName))
	downFilePath := filepath.Join(dir, fmt.Sprintf("%s_%s.down.js", version, migrationName))

	if err := fs.WriteFile(upFilePath, []byte(upSQL)); err != nil {
		return fmt.Errorf("failed to write up migration: %w", err)
	}
	if err := fs.WriteFile(downFilePath, []byte(downSQL)); err != nil {
		return fmt.Errorf("failed to write down migration: %w", err)
	}

	fmt.Printf("Generated MongoDB migration: %s\n", upFilePath)
	return nil
}
